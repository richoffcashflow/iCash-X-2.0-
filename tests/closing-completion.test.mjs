import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {buyerPackageActions,renderBuyerPackage} from '../lib/buyer-disposition.ts';
import {blockerInput,recoveryInput,proceedsInput} from '../lib/deal-completion.ts';
import {propertyGroup} from '../components/workspace-view.ts';
globalThis.fetch=async()=>{throw Error('Local test cannot make provider calls');};
const p={address:'100 Fixture <Lane>',principal:'Example LLC',purchasePriceCents:11500000,assignmentFeeCents:1000000,askingPriceCents:12500000,repairsCents:null,arvCents:null,closingDate:null,businessPhone:'+12145550123',fetchedAt:null,depositCents:200000};
const actions=buyerPackageActions(p);
assert.equal(actions.length,2);
assert.match(decodeURIComponent(actions[0].url),/I want to buy 100 Fixture <Lane> at \$125,000.00 plus closing costs/);
assert.match(actions[0].url,/^sms:\+12145550123\?body=/);
assert.match(buyerPackageActions(p,true)[0].url,/^sms:\+12145550123&body=/);
assert.doesNotMatch(actions.map(a=>a.body).join(' '),/115,000|10,000|assignmentFeeCents|purchasePriceCents/);
for(const change of [{reserved:true},{businessPhone:null},{businessPhone:'javascript:bad'},{businessPhone:'+11234567890'}])assert.deepEqual(buyerPackageActions({...p,...change}),[]);
const html=renderBuyerPackage(p,{ios:true});assert.match(html,/100 Fixture &lt;Lane&gt;/);assert.match(html,/Send your text to start/);assert.match(html,/&amp;body=/);
assert(!renderBuyerPackage({...p,reserved:true}).includes('I’m ready to buy'));
assert(!blockerInput.safeParse({kind:'price',note:'routing number: 123456789'}).success);
assert(!blockerInput.safeParse({kind:'price',note:'Question',askingPriceCents:1}).success);
const id=randomUUID(),updateId=randomUUID();
assert(!recoveryInput.safeParse({journeyId:id,revision:1,resolution:'Confirmed',confirmed:false}).success);
assert(!proceedsInput.safeParse({dealId:id,updateId,receivedDate:'2026-10-11',confirmed:true,amountCents:1}).success,'Receipt amount must come from verified title evidence');
const work={deals:[{id,screening_id:'property',stage:'closed'}],handoffs:[],signing:[],proceedsReceivedDealIds:[]};
assert.equal(propertyGroup('property',work),'waiting');
assert.equal(propertyGroup('property',{...work,proceedsReceivedDealIds:[id]}),'history');
assert.equal(propertyGroup('property',{...work,deals:[{...work.deals[0],stage:'under_contract'}],journeys:[{id,screening_id:'property',state:'collecting',last_progress_at:new Date().toISOString(),wants_assignment:true}]}),'waiting');
console.log('PASS buyer actions: exact agreed total, private prices, mobile draft links, reservation hold, strict inputs and payment-aware grouping. Zero provider calls.');
